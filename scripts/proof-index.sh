#!/usr/bin/env bash
# Writes proof/PROOF.md, an index of every artifact in proof/ tied to the
# commit and CI run that produced it.
set -euo pipefail
cd "$(dirname "$0")/.."

sha="$(git rev-parse HEAD)"
run_url="${GITHUB_SERVER_URL:-https://github.com}/${GITHUB_REPOSITORY:-CloudCorpRecords/password-validation}/actions/runs/${GITHUB_RUN_ID:-local}"
langs=(typescript python cpp go java rust ruby)

{
  echo "# Proof"
  echo
  echo "Everything in this folder is regenerated by CI on every push to \`main\`. Nothing here is hand-edited."
  echo
  echo "| | |"
  echo "|---|---|"
  echo "| Commit | [\`${sha:0:7}\`](../../../commit/$sha) |"
  echo "| CI run | [$run_url]($run_url) |"
  echo "| Generated | $(date -u +'%Y-%m-%d %H:%M UTC') |"
  echo "| Result | $(tail -2 proof/verify.log | head -1) |"
  echo
  echo "## Video"
  echo
  echo "Full run of \`scripts/verify.sh\`: every language's unit tests, then all shared cases. ([MP4](verify-demo.mp4))"
  echo
  echo "![Full verification run](verify-demo.gif)"
  echo
  echo "## Screenshots, one per language"
  echo
  for l in "${langs[@]}"; do
    echo "### $l"
    echo
    echo "![$l: unit tests and shared cases passing](screenshots/$l.png)"
    echo
  done
  echo "## The tests catch real bugs"
  echo
  echo "CI plants a bug in the Python solution (\`len(pwd) < 6\` becomes \`< 5\`), runs the suite, then reverts it."
  echo "The unit tests fail and the cases that hit the length boundary mismatch, so a passing run means the tests actually check something."
  echo
  echo "![Planted bug caught by the tests](screenshots/bug-caught.png)"
  echo
  echo "## Full log"
  echo
  echo "Plain-text output with the exact toolchain versions: [\`verify.log\`](verify.log)"
  echo
  echo '```'
  sed -n '1,/^$/p' proof/verify.log | head -4
  echo '```'
} > proof/PROOF.md
